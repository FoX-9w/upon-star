// 根据上下卦key查找64卦
function findHexagram(upperKey, lowerKey) {
  for (var i = 0; i < Hexagrams.length; i++) {
    if (Hexagrams[i].upper === upperKey && Hexagrams[i].lower === lowerKey) {
      return Hexagrams[i];
    }
  }
  return null;
}

// 根据爻线数组找八卦key
// lines: [bottom, middle, top] (1=阳, 0=阴)
function linesToBagua(lines) {
  var keys = Object.keys(BaguaLines);
  for (var i = 0; i < keys.length; i++) {
    var bl = BaguaLines[keys[i]];
    if (bl[0] === lines[0] && bl[1] === lines[1] && bl[2] === lines[2]) {
      return keys[i];
    }
  }
  return null;
}

// 翻转爻（阳变阴、阴变阳）
function flipLine(line) {
  return line === 1 ? 0 : 1;
}

// 获取六亲（根据卦宫五行和爻地支五行）
// 卦宫五行: 通过八宫归属确定
// 生我者父母，同我者兄弟，我生者子孙，我克者妻财，克我者官鬼
function getLiuqin(gongWuxing, zhiWuxing) {
  if (zhiWuxing === gongWuxing) return '兄弟';
  // 生我
  var shengwo = { '金': '土', '木': '水', '水': '金', '火': '木', '土': '火' };
  if (shengwo[gongWuxing] === zhiWuxing) return '父母';
  // 我生
  var wosheng = { '金': '水', '木': '火', '水': '木', '火': '土', '土': '金' };
  if (wosheng[gongWuxing] === zhiWuxing) return '子孙';
  // 我克
  var woke = { '金': '木', '木': '土', '水': '火', '火': '金', '土': '水' };
  if (woke[gongWuxing] === zhiWuxing) return '妻财';
  // 克我
  var kewo = { '金': '火', '木': '金', '水': '土', '火': '水', '土': '木' };
  if (kewo[gongWuxing] === zhiWuxing) return '官鬼';
  return '';
}

